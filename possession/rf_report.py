"""Random forest evidence (RF) + SHAP against the submitted rule (CS), leave one sample game out.

Pre-registered in docs/worklog.md ("2026-11-16 (random forest + SHAP, RF)"). Writes docs/results/rf_shap.md.

    python possession/rf_report.py          # needs scikit-learn and shap (not part of the submission environment)

Same data, features and smoothing as gbm_report.py. Aggregates only.
"""

import os
import subprocess
import sys
from datetime import datetime, timezone

import numpy as np
import shap
from sklearn.ensemble import RandomForestClassifier

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
sys.path.insert(0, HERE)
sys.path.insert(0, os.path.join(ROOT, "evaluation"))

import evidence  # noqa: E402
import evidence_report as er  # noqa: E402
import gapmodel  # noqa: E402
import gbm_report as gb  # noqa: E402
import possession_metrics as pm  # noqa: E402

RESULT_MD = os.path.join(ROOT, "docs", "results", "rf_shap.md")
N_SHAP = 2000


def make_rf():
    return RandomForestClassifier(n_estimators=200, min_samples_leaf=20, n_jobs=-1, random_state=0)


def shap_rank(model, X, cols):
    """Mean |SHAP| per feature for the home class, on N_SHAP frames (seed 0)."""
    rng = np.random.default_rng(0)
    idx = rng.choice(len(X), size=min(N_SHAP, len(X)), replace=False)
    Xs = np.nan_to_num(X[idx], nan=-1.0)
    values = shap.TreeExplainer(model).shap_values(Xs)
    home = list(model.classes_).index(0)
    v = values[home] if isinstance(values, list) else values[:, :, home]
    return dict(zip(cols, np.abs(v).mean(axis=0)))


def main():
    games = {}
    for g in (1, 2):
        pos, team, ball, dead, halves = gapmodel.load_sample_csv(g)
        ref = er.reference_labels(g, len(ball), dead, halves)
        bd = er.dropout(ball)
        games[g] = dict(pos=pos, team=team, ball=ball, ball_d=bd, halves=halves, ref=ref,
                        X=gb.features(pos, ball, team, halves), Xd=gb.features(pos, bd, team, halves))

    no_cs = [i for i, f in enumerate(gb.FEATURES) if f != "cs_label"]
    cols_no_cs = [gb.FEATURES[i] for i in no_cs]
    results, ranks, raw_acc = {}, {}, {}
    for test in (1, 2):
        tr, te = games[3 - test], games[test]
        live = (tr["ref"] == pm.H) | (tr["ref"] == pm.A)
        y = np.where(tr["ref"][live] == pm.H, 0, 1)
        # NaN -> -1 so the forest sees "missing" as its own value on every sklearn version
        Xtr = np.nan_to_num(tr["X"][live], nan=-1.0)
        rf = make_rf().fit(Xtr, y)
        rf2 = make_rf().fit(Xtr[:, no_cs], y)
        for cond, X, b in (("tracked", te["X"], te["ball"]), ("dropout", te["Xd"], te["ball_d"])):
            Xc = np.nan_to_num(X, nan=-1.0)
            n = len(b)
            preds = {
                "CS": gb.to_pred(evidence.team_labels("CS", te["pos"], b, te["team"], te["halves"]), te["ref"]),
                "RF": gb.to_pred(gb.gb_labels(rf, Xc, te["halves"], n), te["ref"]),
                "RF no rule": gb.to_pred(gb.gb_labels(rf2, Xc[:, no_cs], te["halves"], n), te["ref"]),
            }
            for name, pred in preds.items():
                results[(test, cond, name)] = er.score(te["ref"], pred)
                print(test, cond, name, round(results[(test, cond, name)]["spell"], 4),
                      round(results[(test, cond, name)]["macro"], 4))
        lv = (te["ref"] == pm.H) | (te["ref"] == pm.A)
        Xlv = np.nan_to_num(te["X"][lv], nan=-1.0)
        ytrue = np.where(te["ref"][lv] == pm.H, 0, 1)
        raw_acc[test] = (float((rf.predict(Xlv) == ytrue).mean()),
                         float((rf2.predict(Xlv[:, no_cs]) == ytrue).mean()))
        ranks[(test, "RF")] = shap_rank(rf, te["X"][lv], list(gb.FEATURES))
        ranks[(test, "RF no rule")] = shap_rank(rf2, te["X"][lv][:, no_cs], cols_no_cs)
        print("shap done for test game", test)

    lines = ["# Random forest + SHAP against the submitted rule (CS)", "",
             "Generated by `possession/rf_report.py`. Pre-registered in `docs/worklog.md` "
             "(\"2026-11-16 (random forest + SHAP, RF)\"). Leave one Metrica sample game out; features, reference "
             "and smoothing as in `docs/results/gbm_evidence.md`. No data from our match is used.", "",
             "## Provenance", "",
             "- generated (UTC): {}".format(datetime.now(timezone.utc).strftime("%Y-%m-%d %H:%M:%S")),
             "- git commit: `{}`".format(subprocess.run(["git", "rev-parse", "HEAD"], capture_output=True,
                                                        text=True, cwd=ROOT).stdout.strip()),
             "- possession/rf_report.py sha256: `{}`".format(gb.sha(os.path.abspath(__file__))),
             "- possession/gbm_report.py sha256: `{}`".format(gb.sha(os.path.join(HERE, "gbm_report.py"))),
             "- model: RandomForestClassifier(n_estimators=200, min_samples_leaf=20, random_state=0); NaN as -1",
             "- python {} / numpy {} / scikit-learn {} / shap {}".format(
                 sys.version.split()[0], np.__version__, __import__("sklearn").__version__, shap.__version__), ""]
    methods = ("CS", "RF", "RF no rule")
    for cond, title in (("tracked", "Held-out game, ball as tracked (primary)"),
                        ("dropout", "Held-out game, ball blanked ~40% (robustness)")):
        lines += ["## {}".format(title), "",
                  "| test game | method | spellF1 | 95% band | macroF1 | transF1@25 | team acc | possessions (pred / true) |",
                  "|---|---|---|---|---|---|---|---|"]
        for g in (1, 2):
            for m in methods:
                r = results[(g, cond, m)]
                lines.append("| {} | {} | {:.4f} | {:.3f}-{:.3f} | {:.4f} | {:.4f} | {:.4f} | {} / {} |".format(
                    g, m, r["spell"], r["lo"], r["hi"], r["macro"], r["trans"], r["team"], r["n_pred"], r["n_gt"]))
        lines.append("")
    lines += ["Raw classifier accuracy on held-out live frames, before smoothing: RF {:.4f} / {:.4f}; "
              "RF without the rule feature {:.4f} / {:.4f} (test game 1 / 2).".format(
                  raw_acc[1][0], raw_acc[2][0], raw_acc[1][1], raw_acc[2][1]), ""]
    for m in ("RF", "RF no rule"):
        feats = sorted(ranks[(1, m)], key=lambda f: -(ranks[(1, m)][f] + ranks[(2, m)][f]))
        lines += ["## SHAP, {} (mean |SHAP| for p(home), {} held-out live frames)".format(m, N_SHAP), "",
                  "| feature | test game 1 | test game 2 |", "|---|---|---|"]
        lines += ["| {} | {:.4f} | {:.4f} |".format(f, ranks[(1, m)][f], ranks[(2, m)][f]) for f in feats]
        lines.append("")
    up = all(results[(g, "tracked", "RF")]["spell"] > results[(g, "tracked", "CS")]["spell"] for g in (1, 2))
    mac = all(results[(g, "tracked", "RF")]["macro"] >= results[(g, "tracked", "CS")]["macro"] - 0.01 for g in (1, 2))
    lines += ["## Decision rule (written in advance)", "",
              "- RF spellF1 higher than CS on both held-out games: **{}**".format("yes" if up else "no"),
              "- macroF1 not lower than CS by more than 0.01 on either: **{}**".format("yes" if mac else "no"),
              "- **RF replaces CS: {}**".format("yes" if up and mac else "no"), ""]
    with open(RESULT_MD, "w") as handle:
        handle.write("\n".join(lines))
    print("wrote", RESULT_MD)


if __name__ == "__main__":
    main()
