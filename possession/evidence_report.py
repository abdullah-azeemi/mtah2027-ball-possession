"""Evidence-layer test on Metrica's open sample games 1 and 2, as pre-registered in docs/worklog.md
("2026-11-15 (evidence layer on sample matches)"). Writes docs/results/evidence_layer.md.

    python possession/evidence_report.py

Reference possession comes from the sample games' event data; every variant gets the same reference D
(oracle dead ball), so only the H/A evidence layer is compared. Aggregates only.
"""

import csv
import hashlib
import os
import subprocess
import sys
from datetime import datetime, timezone

import numpy as np

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
sys.path.insert(0, HERE)
sys.path.insert(0, os.path.join(ROOT, "evaluation"))

import evidence  # noqa: E402
import gapmodel  # noqa: E402
import possession_metrics as pm  # noqa: E402

RESULT_MD = os.path.join(ROOT, "docs", "results", "evidence_layer.md")
POSSESSION_EVENTS = {"PASS", "SHOT", "RECOVERY", "SET PIECE", "BALL LOST", "BALL OUT"}
STEPS = (("N", "C"), ("C", "CS"), ("CS", "CSF"), ("CS", "CSR"), ("CSF", "CSFR"))
BOOT = 200


def reference_labels(g, n, dead, halves):
    """Codes H 0, A 1, D 2, X 3 from the event data of sample game g."""
    path = os.path.join(gapmodel.SAMPLE_DIR, "Sample_Game_{}_RawEventsData.csv".format(g))
    marks = np.full(n, -1, dtype=np.int8)
    with open(path) as handle:
        for r in csv.DictReader(handle):
            if r["Type"] in POSSESSION_EVENTS and r["Team"] in ("Home", "Away"):
                f = int(r["Start Frame"]) - 1
                if 0 <= f < n:
                    marks[f] = 0 if r["Team"] == "Home" else 1
    codes = np.full(n, pm.X, dtype=np.int8)
    for first, last in halves:
        seg = marks[first:last + 1]
        last_known = np.maximum.accumulate(np.where(seg >= 0, np.arange(len(seg)), -1))
        filled = np.where(last_known >= 0, seg[np.maximum(last_known, 0)], seg[seg >= 0][0])
        codes[first:last + 1] = filled
        codes[first:last + 1][dead[first:last + 1]] = pm.D
    return codes


def dropout(ball, seed=0, tracked_mean_s=15.0, missing_mean_s=10.0):
    rng = np.random.default_rng(seed)
    out = ball.copy()
    t, on = 0, True
    while t < len(ball):
        length = max(1, int(rng.exponential((tracked_mean_s if on else missing_mean_s) * evidence.FPS)))
        if not on:
            out[t:t + length] = np.nan
        t += length
        on = not on
    return out


def predict(variant, pos, ball, team, halves, ref):
    tl = evidence.team_labels(variant, pos, ball, team, halves)
    pred = np.where(tl == 1, pm.A, pm.H).astype(np.int8)
    pred[ref == pm.D] = pm.D
    pred[ref == pm.X] = pm.X
    return pred


def score(ref, pred):
    r = pm.evaluate(ref, pred, bootstrap_n=BOOT)
    return {"spell": r["spell_f1_mean"], "lo": r["spell_bootstrap_low"], "hi": r["spell_bootstrap_high"],
            "macro": r["macro_f1"], "trans": r["transitions"][25]["f1"], "team": r["team_acc_gt_alive"],
            "n_pred": r["n_pred_spells"], "n_gt": r["n_gt_spells"]}


def sha(path):
    return hashlib.sha256(open(path, "rb").read()).hexdigest()


def main():
    results = {}
    for g in (1, 2):
        pos, team, ball, dead, halves = gapmodel.load_sample_csv(g)
        ref = reference_labels(g, len(ball), dead, halves)
        dropped = dropout(ball)
        for cond, b in (("tracked", ball), ("dropout", dropped)):
            for v in evidence.VARIANTS:
                results[(g, cond, v)] = score(ref, predict(v, pos, b, team, halves, ref))
                print(g, cond, v, {k: round(x, 4) if isinstance(x, float) else x
                                   for k, x in results[(g, cond, v)].items()})

    lines = ["# Evidence layer on Metrica sample games 1 and 2", "",
             "Generated by `possession/evidence_report.py`. Pre-registered in `docs/worklog.md` "
             "(\"2026-11-15 (evidence layer on sample matches)\") before it was run. Reference possession from the "
             "sample games' event data; every variant gets the reference `D` (oracle dead ball), so only the H/A "
             "evidence layer is compared. No data from our match is used.", "", "## Provenance", "",
             "- generated (UTC): {}".format(datetime.now(timezone.utc).strftime("%Y-%m-%d %H:%M:%S")),
             "- git commit: `{}`".format(subprocess.run(["git", "rev-parse", "HEAD"], capture_output=True,
                                                        text=True, cwd=ROOT).stdout.strip()),
             "- possession/evidence.py sha256: `{}`".format(sha(os.path.join(HERE, "evidence.py"))),
             "- possession/evidence_report.py sha256: `{}`".format(sha(os.path.abspath(__file__))),
             "- possession/submit.py sha256: `{}`".format(sha(os.path.join(HERE, "submit.py"))),
             "- python {} / numpy {}".format(sys.version.split()[0], np.__version__), ""]
    for cond, title in (("tracked", "Condition 1 (primary): ball as tracked"),
                        ("dropout", "Condition 2 (robustness): ball blanked ~40% in long stretches")):
        lines += ["## {}".format(title), "",
                  "| game | variant | spellF1 | 95% band | macroF1 | transF1@25 | team acc | possessions (pred / true) |",
                  "|---|---|---|---|---|---|---|---|"]
        for g in (1, 2):
            for v in evidence.VARIANTS:
                r = results[(g, cond, v)]
                lines.append("| {} | {} | {:.4f} | {:.3f}-{:.3f} | {:.4f} | {:.4f} | {:.4f} | {} / {} |".format(
                    g, v, r["spell"], r["lo"], r["hi"], r["macro"], r["trans"], r["team"], r["n_pred"], r["n_gt"]))
        lines.append("")

    lines += ["## Decision rule (written in advance)", "",
              "| step | spellF1 up on both games | macroF1 drop <= 0.01 | kept | dropout: loses > 0.02 on both |",
              "|---|---|---|---|---|"]
    for a, b in STEPS:
        up = all(results[(g, "tracked", b)]["spell"] > results[(g, "tracked", a)]["spell"] for g in (1, 2))
        mac = all(results[(g, "tracked", b)]["macro"] >= results[(g, "tracked", a)]["macro"] - 0.01 for g in (1, 2))
        flag = all(results[(g, "dropout", b)]["spell"] < results[(g, "dropout", a)]["spell"] - 0.02 for g in (1, 2))
        lines.append("| {} -> {} | {} | {} | **{}** | {} |".format(a, b, "yes" if up else "no", "yes" if mac else "no",
                                                                  "yes" if up and mac else "no",
                                                                  "FLAG" if flag else "no"))
    lines.append("")
    with open(RESULT_MD, "w") as handle:
        handle.write("\n".join(lines))
    print("wrote", RESULT_MD)


if __name__ == "__main__":
    main()
